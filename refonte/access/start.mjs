import {createGroupLoot} from './group-loot.mjs';
import {createGateway} from './server.mjs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {pathToFileURL} from 'node:url';
import {createRequire} from 'node:module';
import {readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {createCharacterStore} from './character-store.mjs';
import {loadRulesCatalogue} from './rules-store.mjs';
import {createAdminStore} from './admin-store.mjs';
import {createBestiaryStore} from './bestiary-store.mjs';
import {createCombatStore} from './combat-store.mjs';
import {createGroupStore} from './group-store.mjs';
import {createGroupMessages} from './group-messages.mjs';
import {createAuthAccounts} from './auth-accounts.mjs';
const base=path.dirname(fileURLToPath(import.meta.url));
const appRoot=path.join(base,'atelier');
const {MongoClient}=createRequire('/var/www/myrpgtable/app/api/package.json')('mongodb');
const mongo=new MongoClient(process.env.MONGO_URI,{serverSelectionTimeoutMS:10000});
await mongo.connect();
const collection=mongo.db('myrpgtable').collection('personnages_refonte');
await collection.createIndex({user_id:1,client_id:1},{unique:true});
await collection.createIndex({client_id:1});
const release=JSON.parse(await readFile(path.join(base,'rules-release.json'),'utf8'));
let loaded;
try{loaded=await loadRulesCatalogue(mongo.db('myrpgtable'),release);}catch(error){await mongo.close();throw error;}
const {text:catalogueText,catalogue}=loaded;
const {validateSavedCharacter}=await import(pathToFileURL(path.join(appRoot,'character-storage.mjs')).href);
const characters=createCharacterStore({collection,validate:input=>validateSavedCharacter(input,catalogue),catalogueFingerprint:createHash('sha256').update(catalogueText).digest('hex')});
const accounts=createAuthAccounts({url:process.env.SUPABASE_URL||process.env.VITE_SUPABASE_URL,key:process.env.SUPABASE_SERVICE_ROLE_KEY||process.env.SUPABASE_SECRET_KEY});
const admin=createAdminStore({db:mongo.db('myrpgtable'),rulesVersion:release.id,accounts,characterStore:characters});
const groupCollection=mongo.db('myrpgtable').collection('groupes_refonte');
await groupCollection.createIndex({id:1},{unique:true});
await groupCollection.createIndex({'members.userId':1,updatedAt:-1});
await groupCollection.createIndex({inviteHash:1},{unique:true,partialFilterExpression:{inviteHash:{$type:'string'}}});
await groupCollection.createIndex({mjInviteHash:1},{unique:true,partialFilterExpression:{mjInviteHash:{$type:'string'}}});
const groups=createGroupStore({collection:groupCollection,characters});
const messageCollection=mongo.db('myrpgtable').collection('messages_groupes_refonte');
await messageCollection.createIndex({id:1},{unique:true});
await messageCollection.createIndex({groupId:1,createdAt:-1,id:-1});
await messageCollection.createIndex({unreadIds:1,groupId:1,createdAt:1});
const messages=createGroupMessages({collection:messageCollection,groups});
const {sheetModel}=await import(pathToFileURL(path.join(appRoot,'sheet-model.mjs')).href);
const lootCollection=mongo.db('myrpgtable').collection('butins_groupes_refonte');
await lootCollection.createIndex({id:1},{unique:true});
await lootCollection.createIndex({groupId:1,createdAt:-1,id:-1});
await lootCollection.createIndex({'recipients.userId':1,groupId:1,createdAt:-1});
const loot=createGroupLoot({collection:lootCollection,groups,characters,catalogue,sheetModel:s=>sheetModel(s,catalogue),validate:s=>validateSavedCharacter(s,catalogue)});
const {playView,applyPlayAction}=await import(pathToFileURL(path.join(appRoot,'play-state.mjs')).href);
const combatCollection=mongo.db('myrpgtable').collection('combats_refonte');
await combatCollection.createIndex({id:1},{unique:true});
await combatCollection.createIndex({groupId:1},{unique:true,partialFilterExpression:{active:true}});
await combatCollection.createIndex({groupId:1,updatedAt:-1});
const bestiary=createBestiaryStore({collection:mongo.db('myrpgtable').collection('monstres')});
const spellCollection=mongo.db('myrpgtable').collection('sorts_combats_refonte');
await spellCollection.createIndex({id:1},{unique:true});
await spellCollection.createIndex({groupId:1,combatId:1,createdAt:-1});
const potionCollection=mongo.db('myrpgtable').collection('potions_combats_refonte');
await potionCollection.createIndex({id:1},{unique:true});
await potionCollection.createIndex({groupId:1,combatId:1,createdAt:-1});
const combats=createCombatStore({potionCollection,spellCatalogue:catalogue.spells,collection:combatCollection,spellCollection,groups,characters,bestiary,sheetModel:s=>sheetModel(s,catalogue),playView,applyPlayAction});
const server=createGateway({supabaseUrl:process.env.SUPABASE_URL||process.env.VITE_SUPABASE_URL,anonKey:process.env.SUPABASE_ANON_KEY||process.env.VITE_SUPABASE_KEY,appRoot,characters,groups,combats,bestiary,messages,loot,admin,adminEmails:(process.env.REFONTE_ADMIN_EMAILS||'').split(',').filter(Boolean),catalogueText});
server.on('close',()=>mongo.close());
server.listen(Number(process.env.REFONTE_ACCESS_PORT||4181),'127.0.0.1',()=>console.log('Accès refonte prêt sur la boucle locale.'));
